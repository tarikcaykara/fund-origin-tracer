// Regenerates packages/core/src/labels/confusables.ts, the look-alike letters of spoof detection,
// from the Unicode data files below. Run `bun scripts/confusables.ts` from the repository root and
// commit the result.
import { decomposeSymbol } from "../packages/core/src/labels/spoof.ts";

const UNICODE_VERSION = "18.0.0";
const CONFUSABLES_URL = `https://www.unicode.org/Public/${UNICODE_VERSION}/security/confusables.txt`;
const UNICODE_DATA_URL = `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/UnicodeData.txt`;
const OUT = "packages/core/src/labels/confusables.ts";

async function fetchText(url: string): Promise<string> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

function fromHex(codePoints: string): string {
  return String.fromCodePoint(
    ...codePoints
      .trim()
      .split(/\s+/)
      .map((h) => Number.parseInt(h, 16)),
  );
}

/** [character, Latin capital letter it looks like] */
const candidates: [string, string][] = [];

// `source ; prototype ; MA # comment`. A prototype that is a single Latin letter once its marks
// are removed (Đ → D + overlay) makes the source a look-alike of that letter. The prototype `l`
// stands for every vertical stroke (I, l, 1, |, Greek Ι, Cyrillic І); those fold to I.
for (const line of (await fetchText(CONFUSABLES_URL)).split("\n")) {
  const [source, prototype] = (line.split("#")[0] ?? "").split(";");
  if (source === undefined || prototype === undefined) continue;
  const letter = decomposeSymbol(fromHex(prototype));
  if (!/^[A-Za-z]$/.test(letter)) continue;
  candidates.push([fromHex(source), letter === "l" ? "I" : letter.toUpperCase()]);
}

// Characters named after one Latin letter: small capitals (confusables.txt lists only some of
// them), negative circled and squared letters (the plain circled and squared ones decompose).
// Regional indicators are left out: in pairs they render as flags, not letters.
const LETTER_NAME = /^(?:[A-Z ]+ )?LATIN (?:CAPITAL |SMALL )?LETTER (?:SMALL CAPITAL )?([A-Z])$/;
for (const line of (await fetchText(UNICODE_DATA_URL)).split("\n")) {
  const [code, name] = line.split(";");
  const letter = name?.match(LETTER_NAME)?.[1];
  if (code !== undefined && letter !== undefined) candidates.push([fromHex(code), letter]);
}

// `foldSymbol` looks a character up as it is, so the table is keyed by the source character. It
// strips marks and invisible characters and handles ASCII itself; leave those out, and the
// characters that decomposing and uppercasing already turn into the letter.
const table = new Map<string, string>();
for (const [source, letter] of candidates) {
  if ((source.codePointAt(0) ?? 0) < 0x80) continue;
  const decomposed = decomposeSymbol(source);
  if (decomposed === "" || decomposed.toUpperCase() === letter) continue;
  const known = table.get(source);
  if (known !== undefined && known !== letter) {
    throw new Error(`${source} looks like both ${known} and ${letter}`);
  }
  table.set(source, letter);
}

const byLetter = new Map<string, number[]>();
for (const [key, letter] of table) {
  byLetter.set(letter, [...(byLetter.get(letter) ?? []), key.codePointAt(0) ?? 0]);
}
const rows = [...byLetter.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([letter, cps]) => {
    const hex = cps.sort((a, b) => a - b).map((cp) => `0x${cp.toString(16)}`);
    return `  ${letter}: [${hex.join(", ")}],`;
  });

await Bun.write(
  OUT,
  `// Generated by scripts/confusables.ts from Unicode ${UNICODE_VERSION} confusables.txt and
// UnicodeData.txt; do not edit by hand.

/**
 * Non-ASCII characters that look like a Latin letter, keyed by that capital letter: the
 * confusables.txt entries whose prototype is one Latin letter (vertical strokes count as I), plus
 * the characters named after one Latin letter (small capitals, negative circled and squared
 * letters). Left out: combining marks and invisible characters, and characters that NFKD and
 * uppercasing already turn into the letter.
 */
export const CONFUSABLE_LETTERS: Readonly<Record<string, readonly number[]>> = {
${rows.join("\n")}
};
`,
);
await Bun.$`bunx biome format --write ${OUT}`.quiet();
console.log(`${OUT}: ${table.size} look-alikes of ${byLetter.size} letters`);
